/**
 * @brief TIM输入捕获完成回调函数
 *
 * TIM4_CH1捕获一个完整PWM周期：
 * CCR1保存周期计数值；
 * CCR2保存高电平时间计数值。
 */
void HAL_TIM_IC_CaptureCallback(TIM_HandleTypeDef *htim)
{
  uint32_t period;
  uint32_t high_time;

  if ((htim->Instance == TIM4) &&
      (htim->Channel == HAL_TIM_ACTIVE_CHANNEL_1))
  {
    period = HAL_TIM_ReadCapturedValue(
    htim,
    TIM_CHANNEL_1) + 1U;

high_time = HAL_TIM_ReadCapturedValue(
    htim,
    TIM_CHANNEL_2) + 1U;

    /* 防止周期为0时发生除零错误 */
    if (period != 0U)
    {
      pwm_period_ticks = period;
      pwm_high_ticks = high_time;
      pwm_measurement_valid = 1U;
    }
  }
}

/**
 * @brief 计算PWM参数，并通过USART1发送到电脑
 */
static void UART_LogPwm(uint32_t period_ticks,
                        uint32_t high_ticks)
{
  char message[140];
  int length;

  uint32_t frequency_hz;
  uint32_t duty_x100;

  /*
   * TIM4计数频率为1MHz：
   * 每个计数对应1微秒。
   */
  frequency_hz = 1000000U / period_ticks;

  /*
   * duty_x100表示占空比扩大100倍。
   * 例如5000表示50.00%。
   * 使用uint64_t避免乘法过程中溢出。
   */
  duty_x100 = (uint32_t)(
      ((uint64_t)high_ticks * 10000U) /
      period_ticks);

  length = snprintf(
      message,
      sizeof(message),
      "Freq = %lu Hz, Duty = %lu.%02lu%%, "
      "Period = %lu us, High = %lu us\r\n",
      (unsigned long)frequency_hz,
      (unsigned long)(duty_x100 / 100U),
      (unsigned long)(duty_x100 % 100U),
      (unsigned long)period_ticks,
      (unsigned long)high_ticks);

  if (length > 0)
  {
    HAL_UART_Transmit(
        &huart1,
        (uint8_t *)message,
        (uint16_t)length,
        100U);
  }
}
