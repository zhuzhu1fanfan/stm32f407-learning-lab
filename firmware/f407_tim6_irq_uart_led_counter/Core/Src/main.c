/**
 * @brief 把当前计数值发送到串口
 */
static void UART_LogCount(uint32_t count)
{
  char message[80];
  int length;

  length = snprintf(
      message,
      sizeof(message),
      "TIM6 event: Count = %lu, elapsed = %lu seconds\r\n",
      (unsigned long)count,
      (unsigned long)(count * 2U));

  if (length > 0)
  {
    HAL_UART_Transmit(
        &huart1,
        (uint8_t *)message,
        (uint16_t)length,
        100U);
  }
}
