/**
 * @brief 读取多次ADC并计算平均值
 * @param samples 采样次数
 * @retval ADC平均值，范围0～4095
 */
static uint32_t ADC_ReadAverage(uint32_t samples)
{
  uint32_t sum = 0U;
  uint32_t index;

  if (samples == 0U)
  {
    return 0U;
  }

  for (index = 0U; index < samples; index++)
  {
    /* 启动一次软件触发ADC转换 */
    if (HAL_ADC_Start(&hadc1) != HAL_OK)
    {
      Error_Handler();
    }

    /* 等待ADC转换完成，最大等待10ms */
    if (HAL_ADC_PollForConversion(
            &hadc1,
            10U) != HAL_OK)
    {
      Error_Handler();
    }

    /* 读取12位ADC转换结果 */
    sum += HAL_ADC_GetValue(&hadc1);

    /* 停止本次ADC转换 */
    if (HAL_ADC_Stop(&hadc1) != HAL_OK)
    {
      Error_Handler();
    }
  }

  /* 加上samples/2实现平均值四舍五入 */
  return (sum + samples / 2U) / samples;
}
